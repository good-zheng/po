STYLE = 'Product photography, {} on pure white background, studio lighting, no props, high detail'


def main():
    names = set()
    for f in ['recipes-xiang-a.json', 'recipes-xiang-b.json', 'recipes-chuan.json', 'recipes-gan.json']:
        d = json.load(open(SEED + f, encoding='utf-8'))
        for r in d['recipes']:
            for i in r['ingredients']:
                names.add(i[0])
    mapping = {}
    for n in sorted(names):
        key = ALIAS.get(n, n)
        assert key in IMG, 'no image key for: ' + n
        slug = IMG[key][0]
        mapping[n] = '/api/ingredients/%s.jpg' % slug
    keys = sorted({ALIAS.get(n, n) for n in names})
    with open('D:/pro/po/ingredients-image-list.tsv', 'w', encoding='utf-8') as f:
        for k in keys:
            slug, vis = IMG[k]
            f.write('ing-%s\t%s\n' % (slug, STYLE.format(vis)))
    with open(SEED + 'ingredient-images.json', 'w', encoding='utf-8') as f:
        json.dump(mapping, f, ensure_ascii=False, indent=1)
    print('ingredient names:', len(names))
    print('unique images:', len(keys))


if __name__ == '__main__':
    main()
